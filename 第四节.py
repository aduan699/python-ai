# 3，深浅拷贝
# 3.1:赋值（等于数据完全共享）：一个值的改变会完全被另一个值共享（赋值的对象会随着原对象一起变化）
# li = [1,2,3,4]
# li2 = li
# print('li',li)
# print('li2',li2)
# li.append(5)
# print('li',li)
# print('li2',li2)
# 3.2:浅拷贝（数据半共享）
# 会创建新的对象，拷贝第一层的数据，嵌套层会指向原来的内存地址
# import copy         #***导入copy模块
# li = [1,2,3,[4,5,6]]
# li2 = copy.copy(li)
# print('li',li)
# print('li2',li2)
# ***查看内存地址：id（）
# print('li的内存地址',id(li))
# print('li2的内存地址',id(li2))   #外层的内存地址不一样
# li.append(7)
# print('li',li)
# print('li2',li2)               #运行后只有原来的列表添加了元素，浅拷贝的列表没变
# li[3].append(7)
# print('li',li)
# print('li2',li2)               #运行后浅拷贝对象和原来的对象的内层嵌套中都新增了元素
# print('li[3]的内存地址',id(li[3]))
# print('li2[3]的内存地址',id(li2[3]))   #内层的内存地址是相同的
# ***浅拷贝的优点：拷贝速度快，且占用空间少，拷贝效率高
# 3.3：深拷贝（数据完全不共享）
# 外层的对象和内部的元素都拷贝了一遍
# import copy
# li = [1,2,3,[4,5,6]]
# li2 = copy.deepcopy(li)
# print('li',li,id(li))
# print('li2',li2,id(li2))
# li.append(8)
# print(li)
# print(li2)
# li[3].append(7)
# print(li)
# print(li2)
# 深拷贝数据变化只影响自己本身，跟原来的对象没关联

