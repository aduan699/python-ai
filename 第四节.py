# 1，集合   set
# 1.1：基本格式：集合名 = {元素1，元素2，元素3....}
# s1 = {}     ***定义空字典
# s1 = set()  ***定义空集合
# 1.2：集合具有无序性
# s1 = {'a','b','c','d','e'}
# s2 = {1,2,3,4,5,6}
# print(s1)     ***每次运行的结果都不一样
# print(s2)     ***集合内的元素都是数字时运行的结果每次都一样
# 由于集合有无序性，不能修改集合的值
# 1.3：集合具有唯一性，可以自动去重
# s1 = {1,2,3,4,5,3,2,1}
# print(s1)
# 1.4：集合的常见操作
# 1.4.1：添加元素
# （1）add：添加的是一个整体
# s1 = {1,2,3,4,5}
# s1.add(6)
# s1.add(6，7)     ***一次只能添加一个元素
# print(s1)
# （2）update：把传入的元素拆分，一个个传入集合中
# s1 = {1,2,3,4,5}
# s1.update((6,7))     ***使用update添加元素时，添加的元素必须是可以被for循环取值的可迭代对象
# print(s1)
# s2 = {1,2,3,4,5,6}
# s2.update([7,8])
# print(s2)
# 1.4.2：删除元素
# （1）remove：选择集合中的元素删除，如果有就删除，没有就会报错
# s1 = {1,2,3,4,5}
# s1.remove(1)
# print(s1)
# （2）pop：将集合进行无序排列（若是数字则是有序的），然后删除左边的第一个元素
# s1 = {1,2,3,4,5}
# s1.pop()
# print(s1)
# （3）discard：选择要删除的元素，有就会删除，没有则不会进行任何操作
# s1 = {1,2,3,4,5}
# s1.discard(1)
# print(s1)

